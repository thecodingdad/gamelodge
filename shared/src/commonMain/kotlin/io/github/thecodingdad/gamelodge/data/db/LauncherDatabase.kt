package io.github.thecodingdad.gamelodge.data.db

import androidx.room.Database
import androidx.room.ConstructedBy
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor

@Database(
    entities = [
        LibraryItemEntity::class,
        LaunchTargetEntity::class,
        PlaySessionEntity::class,
        CollectionEntity::class,
        ItemCollectionCrossRef::class,
        HostConfigEntity::class,
        HaTileEntity::class,
        FilterEntity::class,
    ],
    version = 13,
    exportSchema = true,
)
@ConstructedBy(LauncherDatabaseConstructor::class)
abstract class LauncherDatabase : RoomDatabase() {
    abstract fun libraryDao(): LibraryDao
    abstract fun sessionDao(): SessionDao
    abstract fun collectionDao(): CollectionDao
    abstract fun hostConfigDao(): HostConfigDao
    abstract fun haTileDao(): HaTileDao
    abstract fun filterDao(): FilterDao
}

/** Generated by Room for each platform. */
@Suppress("NO_ACTUAL_FOR_EXPECT", "KotlinNoActualForExpect")
expect object LauncherDatabaseConstructor : RoomDatabaseConstructor<LauncherDatabase> {
    override fun initialize(): LauncherDatabase
}

