// Generates every GameLodge app icon from one geometry: the Moonlight logo as a gamepad
// (Moonlight disc as left stick, four face buttons). Run from the repo root:
//   ../.android-dev/jdk17/bin/java tools/icon/IconGen.java
import java.awt.*;
import java.awt.font.GlyphVector;
import java.awt.geom.*;
import java.awt.image.BufferedImage;
import java.io.*;
import java.nio.file.*;
import java.util.*;
import javax.imageio.ImageIO;

public class IconGen {
    static final Color INK = new Color(0x56, 0x5C, 0x64);
    static final Color PAPER = Color.WHITE;
    static final String INK_HEX = "#FF565C64", PAPER_HEX = "#FFFFFFFF", BACKGROUND_HEX = "#FF0E1015";

    // Geometry on a 256 grid.
    static final Area BODY, PAPER_AREA, SPOKES, MONO;

    static {
        Path2D outline = new Path2D.Double();
        outline.moveTo(78, 64);
        outline.curveTo(100, 58, 156, 58, 178, 64);
        outline.curveTo(200, 70, 222, 80, 228, 112);
        outline.curveTo(234, 142, 238, 172, 226, 188);
        outline.curveTo(214, 204, 192, 200, 182, 186);
        outline.curveTo(174, 174, 168, 160, 156, 156);
        outline.curveTo(146, 152, 110, 152, 100, 156);
        outline.curveTo(88, 160, 82, 174, 74, 186);
        outline.curveTo(64, 200, 42, 204, 30, 188);
        outline.curveTo(18, 172, 22, 142, 28, 112);
        outline.curveTo(34, 80, 56, 70, 78, 64);
        outline.closePath();
        BODY = new Area(outline);
        BODY.add(new Area(new BasicStroke(36, BasicStroke.CAP_ROUND, BasicStroke.JOIN_ROUND).createStrokedShape(outline)));

        double sx = 84, sy = 106, sr = 36;
        Area stick = new Area(new Ellipse2D.Double(sx - sr, sy - sr, 2 * sr, 2 * sr));
        Area buttons = new Area();
        for (double[] c : new double[][] {{178, 82}, {202, 106}, {178, 130}, {154, 106}})
            buttons.add(new Area(new Ellipse2D.Double(c[0] - 11, c[1] - 11, 22, 22)));

        Path2D lines = new Path2D.Double();
        for (int i = 0; i < 4; i++) {
            double a = Math.PI / 4 * i, dx = Math.cos(a) * 200, dy = Math.sin(a) * 200;
            lines.moveTo(sx - dx, sy - dy);
            lines.lineTo(sx + dx, sy + dy);
        }
        SPOKES = new Area(new BasicStroke(5, BasicStroke.CAP_BUTT, BasicStroke.JOIN_MITER).createStrokedShape(lines));
        SPOKES.intersect(stick);

        PAPER_AREA = new Area(stick);
        PAPER_AREA.add(buttons);

        MONO = new Area(BODY);
        MONO.subtract(PAPER_AREA);
        MONO.add(SPOKES);
    }

    /** Scales the body's bounds to [width] and centres it on (cx, cy). */
    static AffineTransform fit(double width, double cx, double cy) {
        Rectangle2D b = BODY.getBounds2D();
        double s = width / b.getWidth();
        AffineTransform t = new AffineTransform();
        t.translate(cx, cy);
        t.scale(s, s);
        t.translate(-b.getCenterX(), -b.getCenterY());
        return t;
    }

    static String pathData(Shape shape, AffineTransform t) {
        StringBuilder sb = new StringBuilder();
        double[] c = new double[6];
        for (PathIterator it = shape.getPathIterator(t); !it.isDone(); it.next()) {
            int type = it.currentSegment(c);
            switch (type) {
                case PathIterator.SEG_MOVETO -> sb.append('M').append(n(c[0])).append(',').append(n(c[1]));
                case PathIterator.SEG_LINETO -> sb.append('L').append(n(c[0])).append(',').append(n(c[1]));
                case PathIterator.SEG_QUADTO -> sb.append('Q').append(n(c[0])).append(',').append(n(c[1])).append(' ').append(n(c[2])).append(',').append(n(c[3]));
                case PathIterator.SEG_CUBICTO -> sb.append('C').append(n(c[0])).append(',').append(n(c[1])).append(' ').append(n(c[2])).append(',').append(n(c[3])).append(' ').append(n(c[4])).append(',').append(n(c[5]));
                case PathIterator.SEG_CLOSE -> sb.append('Z');
            }
        }
        return sb.toString();
    }

    static String n(double v) {
        String s = String.format(Locale.ROOT, "%.2f", v);
        s = s.replaceAll("0+$", "").replaceAll("\\.$", "");
        return s.equals("-0") ? "0" : s;
    }

    static String vectorPath(Shape shape, AffineTransform t, String color) {
        return "    <path\n        android:fillColor=\"" + color + "\"\n        android:pathData=\"" + pathData(shape, t) + "\" />\n";
    }

    static String vector(int w, int h, String body) {
        return "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/icon/IconGen.java, do not edit. -->\n"
            + "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
            + "    android:width=\"" + w + "dp\"\n    android:height=\"" + h + "dp\"\n"
            + "    android:viewportWidth=\"" + w + "\"\n    android:viewportHeight=\"" + h + "\">\n" + body + "</vector>\n";
    }

    /** Layered drawing: full body, white stick and buttons, spokes on top (no seams on any background). */
    static String layered(AffineTransform t) {
        return vectorPath(BODY, t, INK_HEX) + vectorPath(PAPER_AREA, t, PAPER_HEX) + vectorPath(SPOKES, t, INK_HEX);
    }

    static BufferedImage render(int size, double margin) {
        BufferedImage img = new BufferedImage(size, size, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = img.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
        g.transform(fit(size * (1 - 2 * margin), size / 2.0, size / 2.0));
        g.setColor(INK); g.fill(BODY);
        g.setColor(PAPER); g.fill(PAPER_AREA);
        g.setColor(INK); g.fill(SPOKES);
        g.dispose();
        return img;
    }

    static BufferedImage banner() {
        int w = 320, h = 180;
        BufferedImage img = new BufferedImage(w, h, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = img.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setRenderingHint(RenderingHints.KEY_STROKE_CONTROL, RenderingHints.VALUE_STROKE_PURE);
        g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
        g.setColor(new Color(0x0E, 0x10, 0x15));
        g.fillRect(0, 0, w, h);
        Font font = new Font("DejaVu Sans", Font.BOLD, 30);
        GlyphVector gv = font.createGlyphVector(g.getFontRenderContext(), "GameLodge");
        Shape text = gv.getOutline();
        Rectangle2D tb = text.getBounds2D();
        double iconW = 84, gap = 14, left = (w - iconW - gap - tb.getWidth()) / 2;
        AffineTransform base = g.getTransform();
        g.transform(fit(iconW, left + iconW / 2, h / 2.0));
        g.setColor(INK); g.fill(BODY);
        g.setColor(PAPER); g.fill(PAPER_AREA);
        g.setColor(INK); g.fill(SPOKES);
        g.setTransform(base);
        g.translate(left + iconW + gap - tb.getX(), h / 2.0 - tb.getCenterY());
        g.setColor(new Color(0xF2, 0xF3, 0xF7));
        g.fill(text);
        g.dispose();
        return img;
    }

    static byte[] png(BufferedImage img) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ImageIO.write(img, "png", out);
        return out.toByteArray();
    }

    /** Windows .ico with PNG-compressed entries (Vista+). */
    static void writeIco(Path file, int... sizes) throws IOException {
        java.util.List<byte[]> images = new ArrayList<>();
        for (int s : sizes) images.add(png(render(s, s <= 32 ? 0.02 : 0.04)));
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        DataOutputStream d = new DataOutputStream(out);
        d.write(le16(0)); d.write(le16(1)); d.write(le16(sizes.length));
        int offset = 6 + 16 * sizes.length;
        for (int i = 0; i < sizes.length; i++) {
            int s = sizes[i];
            d.writeByte(s >= 256 ? 0 : s); d.writeByte(s >= 256 ? 0 : s);
            d.writeByte(0); d.writeByte(0);
            d.write(le16(1)); d.write(le16(32));
            d.write(le32(images.get(i).length)); d.write(le32(offset));
            offset += images.get(i).length;
        }
        for (byte[] b : images) d.write(b);
        Files.write(file, out.toByteArray());
    }

    static byte[] le16(int v) { return new byte[] {(byte) v, (byte) (v >> 8)}; }
    static byte[] le32(int v) { return new byte[] {(byte) v, (byte) (v >> 8), (byte) (v >> 16), (byte) (v >> 24)}; }

    static void write(String file, String content) throws IOException {
        Path p = Paths.get(file);
        Files.createDirectories(p.getParent());
        Files.writeString(p, content);
        System.out.println("wrote " + file);
    }

    public static void main(String[] args) throws Exception {
        // Master SVG.
        AffineTransform id = new AffineTransform();
        write("tools/icon/gamelodge-icon.svg",
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 256 256\">\n"
                + "<path fill=\"#565C64\" d=\"" + pathData(BODY, id) + "\"/>\n"
                + "<path fill=\"#FFFFFF\" d=\"" + pathData(PAPER_AREA, id) + "\"/>\n"
                + "<path fill=\"#565C64\" d=\"" + pathData(SPOKES, id) + "\"/>\n</svg>\n");

        // Android adaptive icon: 108dp canvas, content inside the 66dp safe circle.
        AffineTransform fg = fit(62, 54, 54);
        String res = "app/src/main/res/";
        write(res + "drawable/ic_gamelodge_foreground.xml", vector(108, 108, layered(fg)));
        write(res + "drawable/ic_gamelodge_monochrome.xml", vector(108, 108, vectorPath(MONO, fg, "#FF000000")));
        write(res + "mipmap-anydpi/ic_gamelodge.xml",
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/icon/IconGen.java, do not edit. -->\n"
                + "<adaptive-icon xmlns:android=\"http://schemas.android.com/apk/res/android\">\n"
                + "    <background android:drawable=\"@color/ic_gamelodge_background\" />\n"
                + "    <foreground android:drawable=\"@drawable/ic_gamelodge_foreground\" />\n"
                + "    <monochrome android:drawable=\"@drawable/ic_gamelodge_monochrome\" />\n"
                + "</adaptive-icon>\n");
        write(res + "values/ic_gamelodge.xml",
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by tools/icon/IconGen.java, do not edit. -->\n"
                + "<resources>\n    <color name=\"ic_gamelodge_background\">" + BACKGROUND_HEX + "</color>\n</resources>\n");

        // Android TV banner (320x180, xhdpi): icon + name on the launcher background.
        Files.createDirectories(Paths.get(res + "drawable-xhdpi"));
        ImageIO.write(banner(), "png", new File(res + "drawable-xhdpi/gamelodge_banner.png"));
        System.out.println("wrote " + res + "drawable-xhdpi/gamelodge_banner.png");

        // Desktop: window/tray icon and Windows .ico (exe, installer, shortcuts).
        Files.write(Paths.get("desktop/src/main/resources/icon.png"), png(render(256, 0.04)));
        System.out.println("wrote desktop/src/main/resources/icon.png");
        writeIco(Paths.get("desktop/windows/icon.ico"), 16, 20, 24, 32, 40, 48, 64, 128, 256);
        System.out.println("wrote desktop/windows/icon.ico");

        // Preview for review only.
        if (args.length > 0) ImageIO.write(render(512, 0.04), "png", new File(args[0]));
    }
}
